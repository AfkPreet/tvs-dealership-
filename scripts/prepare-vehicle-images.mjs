/**
 * Turns whatever the download produced into what the site actually serves, and
 * writes content/vehicle-images.json describing it.
 *
 * Two jobs, both cheap and both idempotent:
 *
 *   Renditions. TVS's studio shots come down at 700–800px, and a card shows one
 *   at roughly 250–350 CSS px. Shipping the full file to a card was 40–50KB
 *   each, nineteen times over on the home page. Each image gets narrower
 *   renditions alongside it so a card can ask for the one it needs.
 *
 *   The index. The manifest lists images we intended to have; this lists the
 *   ones on disk. The site reads this, so a model can never point at a picture
 *   that failed to download — the worst case is the typeset plate, which is a
 *   design rather than a broken image.
 *
 * Runs before every build, so neither can drift from the files.
 */
import { readdir, writeFile, unlink } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = process.cwd();
const DIR = path.join(ROOT, 'public', 'vehicles');

/**
 * Narrower cuts, emitted only when the original is genuinely wider.
 *
 * 960 exists because of the gap: a card on a phone at 2.6x device pixels wants
 * around 900px, and without this tier it jumped straight from 720 to the full
 * 1400, which cost two Lighthouse points on the range page for pixels nothing
 * displayed.
 */
const WIDTHS = [400, 720, 960];
const QUALITY = 78;

/** `card.webp` -> `card`, `card-400.webp` -> null (it is a derived file). */
const RENDITION = /-(\d{3,4})\.webp$/;

const index = {};

let slugs = [];
try {
  slugs = (await readdir(DIR, { withFileTypes: true }))
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
} catch {
  // No images downloaded yet. An empty index is a valid state, not an error.
}

let made = 0;

for (const slug of slugs) {
  const dir = path.join(DIR, slug);
  const all = (await readdir(dir)).filter((f) => f.endsWith('.webp'));
  const originals = all.filter((f) => !RENDITION.test(f)).sort();
  if (originals.length === 0) continue;

  const entry = { hero: null, card: null, colours: {}, gallery: [], sizes: {}, widths: {} };

  for (const file of originals) {
    const name = file.replace(/\.webp$/, '');
    const url = `/vehicles/${slug}/${file}`;
    const source = path.join(dir, file);
    const meta = await sharp(source).metadata();
    const width = meta.width ?? 0;
    const height = meta.height ?? 0;

    entry.sizes[url] = { width, height };

    const cuts = WIDTHS.filter((w) => w < width);
    for (const w of cuts) {
      const dest = path.join(dir, `${name}-${w}.webp`);
      if (!all.includes(`${name}-${w}.webp`)) {
        await sharp(source).resize({ width: w }).webp({ quality: QUALITY, effort: 6 }).toFile(dest);
        made += 1;
      }
      entry.sizes[`/vehicles/${slug}/${name}-${w}.webp`] = {
        width: w,
        height: Math.round((height / width) * w),
      };
    }
    entry.widths[url] = [...cuts, width].sort((a, b) => b - a);

    // `hero.webp` is a large studio shot found on a second pass; `card.webp` is
    // the navigation's 372px thumbnail. The hero wins where one exists.
    if (name === 'hero') entry.hero = url;
    else if (name === 'card') entry.card = url;
    else if (/^view-\d+$/.test(name)) entry.gallery.push(url);
    else entry.colours[name] = url;
  }

  // Drop renditions left behind by an image that is no longer downloaded.
  for (const file of all) {
    if (!RENDITION.test(file)) continue;
    const base = file.replace(RENDITION, '.webp');
    if (!originals.includes(base)) await unlink(path.join(dir, file));
  }

  index[slug] = entry;
}

await writeFile(
  path.join(ROOT, 'content', 'vehicle-images.json'),
  JSON.stringify(
    {
      note: 'GENERATED by scripts/prepare-vehicle-images.mjs from the files in public/vehicles/. Do not edit.',
      models: index,
    },
    null,
    2,
  ) + '\n',
);

const colours = Object.values(index).reduce((n, m) => n + Object.keys(m.colours).length, 0);
const gallery = Object.values(index).reduce((n, m) => n + m.gallery.length, 0);
const cards = Object.values(index).filter((m) => m.card || m.hero).length;
const heroes = Object.values(index).filter((m) => m.hero).length;
console.log(
  `${Object.keys(index).length} models — ${cards} cards (${heroes} large), ${colours} colours, ${gallery} views` +
    (made ? `; made ${made} rendition(s)` : ''),
);
