/**
 * Indexes whatever is actually in public/vehicles/ into content/vehicle-images.json.
 *
 * The download manifest lists images we *intend* to have; this lists the ones on
 * disk. The site reads this file, so a model can never point at a picture that
 * failed to download — the worst case is the typeset plate, which is a design,
 * not a broken image.
 *
 * Runs before every build, so the index cannot drift from the files.
 */
import { readdir, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';

const ROOT = process.cwd();
const DIR = path.join(ROOT, 'public', 'vehicles');

const index = {};

let slugs = [];
try {
  slugs = (await readdir(DIR, { withFileTypes: true }))
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
} catch {
  // No images downloaded yet. An empty index is a valid state, not an error.
}

for (const slug of slugs) {
  const files = (await readdir(path.join(DIR, slug))).filter((f) => f.endsWith('.webp')).sort();
  if (files.length === 0) continue;

  const entry = { card: null, colours: {}, gallery: [] };
  for (const file of files) {
    const name = file.replace(/\.webp$/, '');
    const url = `/vehicles/${slug}/${file}`;
    if (name === 'card') entry.card = url;
    else if (/^view-\d+$/.test(name)) entry.gallery.push(url);
    else entry.colours[name] = url;
  }
  index[slug] = entry;
}

await writeFile(
  path.join(ROOT, 'content', 'vehicle-images.json'),
  JSON.stringify(
    {
      note: 'GENERATED by scripts/index-vehicle-images.mjs from the files in public/vehicles/. Do not edit.',
      models: index,
    },
    null,
    2,
  ) + '\n',
);

const colours = Object.values(index).reduce((n, m) => n + Object.keys(m.colours).length, 0);
const gallery = Object.values(index).reduce((n, m) => n + m.gallery.length, 0);
const cards = Object.values(index).filter((m) => m.card).length;
console.log(`indexed ${Object.keys(index).length} models — ${cards} cards, ${colours} colours, ${gallery} views`);
